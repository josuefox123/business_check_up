/**
 * QuestionBankSeeder v2 — format normalisé.
 *
 * CONVENTIONS (v1.1) :
 * - Tous les slugs (options 'value', 'question_id', codes) sont en ASCII sans accents, snake_case.
 * - 'followup_trigger' est une LISTE de déclencheurs évaluables par Question::checkFollowups() :
 *     ['field' => 'score'|'value'|'values'|'values_count',
 *      'operator' => '<='|'<'|'>='|'>'|'='|'!='|'in'|'not_in'|'intersects'|'contains_all'|'not_intersects',
 *      'value' => mixed,
 *      'question_id' => string,
 *      'text' => string,
 *      'options' => array|null]   // options de la question de suivi, le cas échéant
 * - 'red_flag_conditions' est une LISTE de conditions évaluables par Question::checkRedFlag() :
 *     ['field' => ..., 'operator' => ..., 'value' => ..., 'code' => string]
 * - Règle de cohérence : une condition 'score' n'est utilisée QUE si toutes les options
 *   de la question portent un 'score'. Sinon on utilise 'value' / 'values' / 'values_count'.
 * - updateOrCreate(question_id + version) : le seeder est rejouable sans vider la table.
 */
