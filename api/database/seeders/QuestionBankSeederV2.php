    public function run(): void
    {
        $this->seedTriageQuestions();
        $this->seedFlashQuestions();
        $this->seedDifficultyQuestions();
        $this->seedOpportunityQuestions();
        $this->seedProductQuestions();
        $this->seedCommercialQuestions();
        $this->seedFinanceQuestions();
        $this->seedGovernanceQuestions();
        $this->seedProjectQuestions();
        $this->seed360Questions();
    }

    /**
     * Insertion idempotente : met à jour si (question_id, version) existe déjà.
     */
    private function persist(array $questions, string $moduleCode, string $version = 'v1.1'): void
    {
        foreach ($questions as $q) {
            Question::updateOrCreate(
                ['question_id' => $q['question_id'], 'version' => $version],
                array_merge($q, ['module_code' => $moduleCode, 'version' => $version])
            );
        }
    }

