 *
 * RÈGLE D\'OR (fichier source) : ces questions enrichissent le rapport et la
 * préparation du rendez-vous ; elles ne modifient NI le routage, NI le score,
 * NI la bande de résultat. D\'où pour toutes : score_logic = no_score,
 * weight = 0, dimension = meta, is_required = false, aucun red flag,
 * aucun followup_trigger (les conditions d\'affichage sont stockées dans
 * enrichment_meta.display_condition, en langage métier).
 *
 * Distinction avec les questions de diagnostic :
 *   - bc_questions.question_kind = \'enrichment\' (vs \'diagnostic')
 *   - bc_questions.req_level    = 'core\' | \'conditional\'
 *   - détails spécifiques REQ dans bc_question_enrichment_meta (relation 1-1).
 *
 * Rejouable : updateOrCreate sur (question_id, version) + meta liée.
 */
class EnrichmentQuestionSeeder extends Seeder
{
    private const VERSION = 'v1.0';

    public function run(): void
    {
        $req = $this->questions();

        foreach ($req as $q) {
            $meta = $q['enrichment'];
            unset($q['enrichment']);
            $module = $q['module_code'];
            unset($q['module_code']);

            $question = Question::updateOrCreate(
                ['question_id' => $q['question_id'], 'version' => self::VERSION],
                array_merge($q, [
                    'module_code' => $module,
                    'version'     => self::VERSION,
                ])
            );

            QuestionEnrichmentMeta::updateOrCreate(
                ['question_db_id' => $question->question_id],
                $meta
            );
        }
    }

